package dev.yveskalume.elevenlabs.feature.multicontext

import dev.yveskalume.elevenlabs.feature.LoadingState
import dev.yveskalume.elevenlabs.voices.Voice

enum class Playback {
    Stopped,

    /** Opening the connection. */
    Connecting,
    Reading,
}

enum class ContextStatus {
    /** Text sent; ElevenLabs is still generating audio. */
    Generating,

    /** All audio generated and waiting to be played. */
    Ready,
    Playing,
}

/** A paragraph being generated in its own context on the shared connection. */
data class ContextSlot(
    val contextId: String,
    val paragraph: Int,
    val fromLine: Int,
    val status: ContextStatus,
    /** Audio received so far. */
    val audioMillis: Long,
)

/** How quickly audio started after the user jumped to a line. */
data class JumpReport(
    /** Whether the line's paragraph had already been generated by a look-ahead context. */
    val fromLookAhead: Boolean,
    val firstAudioMillis: Long,
)

data class MultiContextUiState(
    val voices: LoadingState<List<Voice>> = LoadingState.Loading,
    val selectedVoiceId: String? = null,
    val book: Book = AesopsFables,
    val playback: Playback = Playback.Stopped,
    /** The line being read, or where reading resumes. */
    val currentLine: Int = 0,
    /** Whether the book was read to the end, so playing again starts over. */
    val ended: Boolean = false,
    /** Paragraphs on the connection, current first. At most `MultiContextTtsSession.MAX_CONTEXTS`. */
    val contexts: List<ContextSlot> = emptyList(),
    /** The last paragraph whose audio started going to the player, or -1. */
    val bufferedParagraph: Int = -1,
    /** How many paragraphs after the current one are generated ahead of time. */
    val lookAhead: Int = 2,
    val lastJump: JumpReport? = null,
    val error: String? = null,
) {
    val selectedVoice: Voice?
        get() = voices.dataOrNull?.firstOrNull { it.id == selectedVoiceId }
            ?: voices.dataOrNull?.firstOrNull()

    /** Whether audio for [line] has already been received, so jumping there is instant. */
    fun isPrepared(line: Int): Boolean {
        val target = book.lines[line]
        if (target.paragraph <= bufferedParagraph) return true
        return contexts.any { it.paragraph == target.paragraph && it.fromLine <= line && it.audioMillis > 0 }
    }
}
